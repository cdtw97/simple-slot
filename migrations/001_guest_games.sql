CREATE TABLE IF NOT EXISTS slot_guests (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  secret_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  profile_json MEDIUMTEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS slot_games (
  guest_id BIGINT UNSIGNED NOT NULL,
  mode VARCHAR(12) NOT NULL,
  state_json MEDIUMTEXT NOT NULL,
  PRIMARY KEY (guest_id, mode),
  FOREIGN KEY (guest_id) REFERENCES slot_guests(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS slot_actions (
  guest_id BIGINT UNSIGNED NOT NULL,
  action_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_hash CHAR(64) CHARACTER SET ascii NOT NULL,
  receipt_json MEDIUMTEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (guest_id, action_id),
  FOREIGN KEY (guest_id) REFERENCES slot_guests(id) ON DELETE CASCADE
) ENGINE=InnoDB;
